export const LANGS = { en, fr, iu };
export const LANG_OPTIONS = [
  { code: 'en', label: 'English' },
  { code: 'fr', label: 'Français' },
  { code: 'iu', label: 'ᐃᓄᒃᑎᑐᑦ' },
];

/**
 * Translate. Returns {text, lang} where lang is the language actually used,
 * so the DOM can mark English fallbacks with lang="en".
 */
export function translate(lang, key, vars) {
  let dict = LANGS[lang] || en;
  let used = lang;
  let str = dict[key];
  if (str === undefined) {
    str = en[key];
    used = 'en';
  }
  if (str === undefined) {
    str = key;
    used = 'en';
  }
  if (vars) str = str.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  return { text: str, lang: used };
}
