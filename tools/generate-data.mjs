/** Tank % consumed between two times for a household (simple day/night use model). */
function consumedPct(h, fromMs, toMs) {
  const daily = h.occ * LITRES_PER_PERSON_DAY;
  let pct = 0;
  for (let t = fromMs; t < toMs; t += 10 * 60_000) {
    const hour = new Date(t).getUTCHours();
    const dt = Math.min(10 * 60_000, toMs - t) / 3600_000;
    pct += (daily * hourWeight(hour) * dt * 100) / h.cap;
  }
  return pct;
}

function timeline(h, seed) {
  const rand = prng(seed);
  const jitter = (amp) => (rand() * 2 - 1) * amp;
  const fillTime = hoursBefore(h.fillHoursAgo).getTime();
  const baseWater = { turbidity: 0.42, conductivity: 85 + Math.round(jitter(4)), temperature: 14.2 };
  const readings = [];
  const lastIndex = h.monitorOfflineHours ? N - 1 - (h.monitorOfflineHours * 60) / STEP_MIN : N - 1;
  for (let i = 0; i <= lastIndex; i++) {
    const t = new Date(END.getTime() - (N - 1 - i) * STEP_MIN * 60_000);
    const ms = t.getTime();
    const hour = t.getUTCHours() + t.getUTCMinutes() / 60;
    let level;
    let water = { ...baseWater };
    let settle = Infinity;
    if (ms >= fillTime) {
      level = h.fill - consumedPct(h, fillTime, ms);
      settle = (ms - fillTime) / (STEP_MIN * 60_000);
    } else {
      // Before the delivery in the recording: tank drains down to `pre`.
      level = (h.pre ?? 30) + consumedPct(h, ms, fillTime) * 0.98;
    }
    // Freshly delivered water is colder and slightly more turbid; it settles over hours.
    let temperature = Number.isFinite(settle) ? 14.5 - 5 * Math.exp(-settle / 6) : water.temperature;
    temperature += 0.25 * Math.sin(((hour - 15) / 24) * 2 * Math.PI);
    const turbidity = Number.isFinite(settle) ? 0.4 + 0.18 * Math.exp(-settle / 2) : water.turbidity;
    const r = {
      timestamp: iso(t),
      turbidity: round(Math.max(0.05, turbidity + jitter(0.05)), 2),
      conductivity: round(water.conductivity + (Number.isFinite(settle) ? 2 : 0) + jitter(1.2), 0),
      temperature: round(temperature + jitter(0.1), 1),
      tankLevel: round(Math.max(0, Math.min(100, level + jitter(0.15))), 1),
    };
    readings.push(r);
  }
  const at = (hoursAgo) => readings[N - 1 - Math.round((hoursAgo * 60) / STEP_MIN)];
  if (h.anomaly) {
    // A short turbidity episode about 20 hours ago that returns to normal.
    at(20.5).turbidity = 1.92;
    at(20).turbidity = 1.74;
  }
  if (h.changedNow) {
    readings[readings.length - 2].turbidity = 2.08;
    readings[readings.length - 1].turbidity = 2.21;
  }
  if (h.sensorFailure) {
    for (const r of readings.slice(-3)) r.turbidity = null;
  }
  return readings;
}

export function buildAll() {
  const meta = (extra = {}) => ({ synthetic: true, note: SYNTHETIC_NOTE, ...extra });

  const households = {
    _meta: meta({ litresPerPersonPerDay: LITRES_PER_PERSON_DAY }),
    households: HOUSEHOLDS.map((h) => ({
      id: h.id,
      displayName: h.id,
      sensorDevice: `IMQ-${h.id.slice(2).padStart(4, '0')}`,
      // Top-mounted distance sensor geometry (prototype: upright tank, volume ∝ height).
      tankHeightCm: TANK_HEIGHT_CM[h.cap],
      assignedTruck: h.truck,
      tankCapacityLitres: h.cap,
      occupants: h.occ,
      estimatedDailyUseLitres: h.occ * LITRES_PER_PERSON_DAY,
      vulnerability: h.vulnerability || null,
      deliveryIntervalDays: h.interval,
      // Reference "normal" conditions from commissioning; refreshed after each delivery.
      baseline: { turbidity: 0.42, conductivity: 86, temperature: 14.2 },
    })),
  };

  const readings = {
    _meta: meta({ intervalMinutes: STEP_MIN, recordingEnd: iso(END) }),
    households: Object.fromEntries(HOUSEHOLDS.map((h, i) => [h.id, timeline(h, 100 + i)])),
  };

  const deliveries = {
    _meta: meta(),
    deliveries: HOUSEHOLDS.map((h) => ({
      id: `D-SEED-${h.id}`,
      householdId: h.id,
      truckId: h.truck,
      litres: h.fillLitres,
      timestamp: iso(hoursBefore(h.fillHoursAgo)),
    })).sort((a, b) => a.timestamp.localeCompare(b.timestamp)),
  };

  const trucks = { _meta: meta(), trucks: TRUCKS.map((t) => ({ ...t, displayName: `Truck ${t.id}` })) };
  const sensors = {
    _meta: meta(),
    sensors: [
      ...HOUSEHOLDS.map((h, i) => ({
        id: `IMQ-${h.id.slice(2).padStart(4, '0')}`,
        householdId: h.id,
        firmwareVersion: '0.3.1-proto',
        batteryPercent: 96 - ((i * 7) % 23),
      })),
      // A spare, unassigned monitor in municipal stock (for registration/assignment).
      { id: 'IMQ-0100', householdId: null, firmwareVersion: '0.3.1-proto', batteryPercent: 100 },
    ],
  };
  const alerts = { _meta: meta(), alerts: [] };
  const municipality = {
    _meta: meta(),
    community: 'Inukjuak',
    communitySyllabics: 'ᐃᓄᑦᔪᐊᖅ',
    villageWaterCubicMetres: 320,
    villageWaterCapacityCubicMetres: 500,
    maxStopsPerTruckPerDay: 6,
  };

  return {
    'households.json': households,
    'readings.json': readings,
    'deliveries.json': deliveries,
    'trucks.json': trucks,
    'sensors.json': sensors,
    'alerts.json': alerts,
    'municipality.json': municipality,
  };
}

