/**
 * Generates the SYNTHETIC seed data in data/.
 *
 * Run: node tools/generate-data.mjs
 *
 * - Seeded PRNG, so output is identical on every run (a unit test checks this).
 * - Randomness exists ONLY here, at build time. The app never calls Math.random().
 * - Values are illustrative. They are NOT measurements from Inukjuak or any real household.
 */
import { writeFile, mkdir, rm } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const STEP_MIN = 30;
const HOURS = 48;
const N = (HOURS * 60) / STEP_MIN + 1; // 97 readings per household
const LITRES_PER_PERSON_DAY = 60;
// Nominal end of the recording. The app replays the recording relative to when it is first opened.
const END = new Date(Date.UTC(2026, 8, 26, 12, 42));
const SYNTHETIC_NOTE =
  'SYNTHETIC SAMPLE DATA generated by tools/generate-data.mjs for a hackathon prototype. Not real measurements. No household water-quality data from Inukjuak is represented.';

function prng(seed) {
  let s = seed >>> 0;
  return () => ((s = (s * 1664525 + 1013904223) >>> 0) / 2 ** 32);
}
const pad = (n) => String(n).padStart(2, '0');
/** Wall-clock ISO string without zone (the app rebases all recorded times). */
function iso(date) {
  return `${date.getUTCFullYear()}-${pad(date.getUTCMonth() + 1)}-${pad(date.getUTCDate())}T${pad(date.getUTCHours())}:${pad(date.getUTCMinutes())}:00`;
}
const hoursBefore = (h) => new Date(END.getTime() - h * 3600_000);
const round = (v, d) => Math.round(v * 10 ** d) / 10 ** d;

/** Share of daily use per hour: 90 % between 07:00 and 22:00, 10 % overnight. */
const hourWeight = (hour) => (hour >= 7 && hour < 22 ? 0.9 / 15 : 0.1 / 9);

